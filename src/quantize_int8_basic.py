import os
import glob
import argparse
import tensorflow as tf

def representative_data_gen(dataset, n_samples=100):
    """Generator yielding dataset samples to calibrate INT8 activation ranges.

    IMPORTANT: the dataset must ALWAYS come from the training split
    (data/splits/train). Calibrating on test images would fit the activation
    ranges (scale/zero_point) to the evaluation distribution, biasing SIL, PIL,
    and HIL accuracy upward.
    """
    def gen():
        # n_samples images, yielded one by one as expected by TFLiteConverter
        for images, _ in dataset.unbatch().batch(1).take(n_samples):
            yield [images]
    return gen

def main():
    parser = argparse.ArgumentParser(description="Quantize a Keras model to full-integer INT8.")
    parser.add_argument("--model_path", type=str, help="Path to the .keras model to quantize")
    parser.add_argument("--splits_dir", type=str, default="data/splits",
                        help="Directory holding the splits generated by split_dataset.py "
                             "(calibration uses ONLY <splits_dir>/train)")
    parser.add_argument("--calib_samples", type=int, default=100,
                        help="Number of calibration images drawn from the train split")
    parser.add_argument("--calib_seed", type=int, default=42,
                        help="Random seed for calibration shuffling; fixes the generated .tflite")
    args = parser.parse_args()

    if args.model_path:
        model_path = args.model_path
        if not os.path.exists(model_path):
            print(f"Error: Model not found at {model_path}.")
            return
    else:
        checkpoints = glob.glob("models/checkpoints/*.keras")
        if not checkpoints:
            print("Error: No (.keras) models found in models/checkpoints.")
            print("Make sure you have trained a model first.")
            return

        # Use the first checkpoint found when --model_path is omitted
        model_path = checkpoints[0]

    print(f"Model selected for quantization: {model_path}")

    # Extract basename to preserve full model identity (including any _pruned suffix)
    # Expected format example: MobileNetV2+32+20+0.0001+160+120.keras
    basename = os.path.basename(model_path).replace(".keras", "")

    # Strip any pruning suffix on a temporary stem only when parsing WxH dimensions
    dim_stem = basename.split("_pruned")[0]
    parts = dim_stem.split('+')

    # Current format (without validation_split): {model}+{batch}+{epochs}+{lr}+{W}+{H} -> 6 parts
    # Legacy format (with validation_split):                                           -> 7 parts
    try:
        if len(parts) >= 6:
            width = int(parts[-2])
            height = int(parts[-1])
        else:
            raise ValueError("fewer than 6 '+'-separated fields")
    except ValueError:
        print("Could not infer dimensions from filename. Defaulting to 160x120.")
        width, height = 160, 120

    # Calibration uses EXCLUSIVELY the training split.
    # Never test (which would leak evaluation distribution) and never val
    # (already consumed by EarlyStopping and ReduceLROnPlateau for model selection).
    data_dir = os.path.join(args.splits_dir, "train")

    if not os.path.exists(data_dir):
        print(f"Error: training split not found at {data_dir}.")
        print("Generate the dataset splits first:")
        print(f"  python src/split_dataset.py --input_dir data/processed/{width}x{height}"
              f" --output_dir {args.splits_dir}")
        return

    print(f"\nCalibrating with {args.calib_samples} images from {data_dir} "
          f"(seed {args.calib_seed})...")
    calib_ds = tf.keras.utils.image_dataset_from_directory(
        data_dir,
        # no validation_split or subset: the directory IS already the train split
        shuffle=True,            # required: files on disk are grouped by class
        seed=args.calib_seed,    # fixed seed makes calibration shuffling reproducible
        color_mode='grayscale',
        image_size=(height, width),
        batch_size=32
    )

    print("\nLoading model...")
    model = tf.keras.models.load_model(model_path)

    print("\nConfiguring Full Integer Quantization (INT8) conversion...")
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]

    # Provide the representative dataset (mandatory for full-INT8 conversion)
    converter.representative_dataset = representative_data_gen(calib_ds, args.calib_samples)

    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]

    # Set INT8 input and output tensors for maximum Edge/MCU compatibility
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8

    print("Converting model. This will take a few seconds...")
    try:
        tflite_model = converter.convert()

        tflite_dir = "models/tflite"
        os.makedirs(tflite_dir, exist_ok=True)

        out_path = os.path.join(tflite_dir, f"{basename}_int8.tflite")
        with open(out_path, "wb") as f:
            f.write(tflite_model)

        print("\nConversion successful!")
        print(f"Model saved to: {out_path}")
        print(f"Final size: {len(tflite_model) / 1024:.2f} KB")

    except Exception as e:
        print(f"\nError during conversion (possible unsupported operations): {e}")

if __name__ == "__main__":
    main()
